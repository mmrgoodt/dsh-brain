/** token → 同组其他 token 的集合 */
const INDEX = new Map();
for (const g of GROUPS) {
  for (const w of g) {
    let s = INDEX.get(w);
    if (!s) { s = new Set(); INDEX.set(w, s); }
    for (const o of g) if (o !== w) s.add(o);
  }
}

/**
 * 把一组 token 扩展进同义词。
 * @param {Set<string>} toks
 * @param {number} cap 最多扩到多少个（防爆）
 */
export function expand(toks, cap = 120) {
  if (!toks || !toks.size) return toks;
  const out = new Set(toks);
  for (const t of toks) {
    const syn = INDEX.get(t);
    if (!syn) continue;
    for (const s of syn) {
      if (out.size >= cap) return out;
      out.add(s);
    }
  }
  return out;
}

export function groups() {
  return GROUPS.length;
}
